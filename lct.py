"""Aplicación de Hybrid Search con Reciprocal Rank Fusion (RRF), para combinar los resultados anteriores:"""

def hybrid_search(query, top_k=10, k_rrf=60):

    # ==========================
    # FAISS
    # ==========================

    faiss_scores, faiss_indices = buscar(
        query,
        top_k=top_k
    )

    # ==========================
    # BM25
    # ==========================

    bm25_scores, bm25_indices = buscar_bm25(
        query,
        top_k=top_k
    )

    # ==========================
    # Reciprocal Rank Fusion
    # ==========================

    fusion_scores = {}

    # Ranking FAISS
    for rank, idx in enumerate(faiss_indices):

        fusion_scores[idx] = (
            fusion_scores.get(idx, 0)
            + 1 / (k_rrf + rank + 1)
        )

    # Ranking BM25
    for rank, idx in enumerate(bm25_indices):

        fusion_scores[idx] = (
            fusion_scores.get(idx, 0)
            + 1 / (k_rrf + rank + 1)
        )

    # ==========================
    # Ordenar ranking final
    # ==========================

    ranking_final = sorted(
        fusion_scores.items(),
        key=lambda x: x[1],
        reverse=True
    )

    return ranking_final

