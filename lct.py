"""Chunking
Reglas:
1. Respetar estructura jurídica de divisón por títulos y capítulos, por lo que el corte se realizaría en primer lugar por títulos y capítulos.
2. Cuando el capítulo supere las 800 palabras, realizaremos el corte en 800 palabras con overlap de 50 palabras.


"""

MAX_WORDS = 800
OVERLAP = 50

chunks_finales = []

for seccion in secciones:

    palabras = seccion["texto"].split()

    # Caso 1: la sección entra completa
    if len(palabras) <= MAX_WORDS:

        chunks_finales.append({
            "titulo": seccion["titulo"],
            "titulo_nombre": seccion["titulo_nombre"],
            "capitulo": seccion["capitulo"],
            "capitulo_nombre": seccion["capitulo_nombre"],
            "chunk_id": 1,
            "texto": seccion["texto"],
            "word_count": len(palabras)
        })

    # Caso 2: hay que dividir
    else:

        inicio = 0
        chunk_id = 1

        while inicio < len(palabras):

            fin = min(inicio + MAX_WORDS, len(palabras))

            chunk_words = palabras[inicio:fin]

            chunks_finales.append({
                "titulo": seccion["titulo"],
                "titulo_nombre": seccion["titulo_nombre"],
                "capitulo": seccion["capitulo"],
                "capitulo_nombre": seccion["capitulo_nombre"],
                "chunk_id": chunk_id,
                "texto": " ".join(chunk_words),
                "word_count": len(chunk_words)
            })

            if fin >= len(palabras):
                break

            inicio = fin - OVERLAP
            chunk_id += 1

