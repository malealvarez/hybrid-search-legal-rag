import re

def limpiar_texto(texto):

    # Eliminar sección Antecedentes Normativos
    texto = re.sub(
        r'Antecedentes Normativos.*$',
        '',
        texto,
        flags=re.DOTALL | re.IGNORECASE
    )

    # Eliminar anotaciones editoriales
    patrones = [
        r'\(Nota Infoleg.*?\)',
        r'\(Capítulo.*?\)',
        r'\(Artículo.*?\)',
        r'\(Inciso.*?\)',
        r'\(Párrafo.*?\)',
        r'\(Denominación.*?\)'
    ]

    for patron in patrones:
        texto = re.sub(
            patron,
            '',
            texto,
            flags=re.DOTALL | re.IGNORECASE
        )

    # Normalizar espacios
    texto = re.sub(r'[ \t]+', ' ', texto)

    # Normalizar saltos de línea
    texto = re.sub(r'\n{3,}', '\n\n', texto)

    return texto.strip()

